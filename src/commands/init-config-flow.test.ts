/**
 * Characterization tests for the config generation in `kit init` (generateConfigFile in
 * setup.ts). They pin the observable flow before the function is split into helpers: stack
 * detection output, the low-confidence guard, the plaintext-secret warning, the secret-backend
 * choice, the seeded keys, the preview, the written file and the closing vault notes.
 *
 * Every run uses `--non-interactive --no-setup`: kit stops after `.kit.toml` and the lock
 * files, and no prompt can appear. The lock files are created up front, so the run does not
 * resolve any tool version. Each run has a disposable HOME and a disposable git repo. The
 * prompt branches (service picker, backend picker, write confirmation) need a TTY and are not
 * pinned here.
 *
 * The suite skips on win32: the fixtures and the CLI spawn expect a POSIX shell layout.
 */
import { describe, it, beforeEach, afterEach } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runCli, type CliResult } from "../cli-run.test-support.js";
import { rmTemp } from "../temp-cleanup.test-support.js";

const skip = process.platform === "win32" ? "fixtures need a POSIX layout" : false;

const ANSI = /\x1b\[[0-9;]*m/g;
const plain = (s: string) => s.replace(ANSI, "");

interface Fixture {
  dir: string;
  home: string;
}

function makeFixture(): Fixture {
  const root = mkdtempSync(join(tmpdir(), "kit-initcfg-char-"));
  const dir = join(root, "repo");
  const home = join(root, "home");
  mkdirSync(dir);
  mkdirSync(home);
  execFileSync("git", ["init", "-q", dir]);
  mkdirSync(join(dir, ".kit"));
  writeFileSync(join(dir, ".kit", "skills-lock.json"), "{}");
  writeFileSync(join(dir, ".kit", "cli-lock.json"), "{}");
  return { dir, home };
}

function file(f: Fixture, name: string, body: string): void {
  writeFileSync(join(f.dir, name), body);
}

async function init(f: Fixture, args: string[] = []): Promise<CliResult & { out: string }> {
  const r = await runCli(["init", "--non-interactive", "--no-setup", ...args], f.dir, {
    HOME: f.home,
    USERPROFILE: f.home,
    KIT_WRAPPER_ALLOW_DEV: "1",
  });
  return { ...r, out: plain(r.stdout + r.stderr) };
}

function written(f: Fixture): string {
  return readFileSync(join(f.dir, ".kit.toml"), "utf-8");
}

let f: Fixture;
function useFixture(): void {
  beforeEach(() => {
    f = makeFixture();
  });
  afterEach(() => {
    rmTemp(join(f.dir, ".."));
  });
}

describe("kit init config generation: detection and guard", { skip }, () => {
  useFixture();

  it("refuses to generate when nothing is detected and nobody can answer", async () => {
    const r = await init(f);
    assert.notEqual(r.exitCode, 0);
    assert.match(r.out, /No \.kit\.toml found\./);
    assert.match(r.out, /confidence too low \(0%\)/);
    assert.match(r.out, /Create a \.kit\.toml manually or run 'kit init' interactively\./);
    assert.equal(existsSync(join(f.dir, ".kit.toml")), false);
  });

  it("writes the config and names the detected stack with its confidence", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /Detected: python \/ flask {2}\(confidence: 85%\)/);
    assert.doesNotMatch(r.out, /Low confidence/);
    assert.match(r.out, /Preview — \.kit\.toml/);
    assert.match(r.out, /Generated \.kit\.toml/);
    assert.match(r.out, /Setup skipped \(--no-setup\)/);
    assert.match(written(f), /^# Detected: python \/ flask$/m);
  });

  it("warns below 70 percent and says where to correct the language", async () => {
    file(f, "pyproject.toml", '[project]\nname = "x"\n');
    const r = await init(f);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /Detected: python {2}\(confidence: 50%\)/);
    assert.match(
      r.out,
      /Low confidence — if this is wrong, set the right language under \[project\]/,
    );
    assert.equal(existsSync(join(f.dir, ".kit.toml")), true);
  });

  it("prints the preview with a plus sign on each line and keeps blank lines blank", async () => {
    file(f, "go.mod", "module x\n");
    const r = await init(f);
    const lines = r.out.split("\n");
    const start = lines.findIndex((l) => l.includes("Preview — .kit.toml"));
    const end = lines.findIndex((l) => l.includes("Generated .kit.toml"));
    const preview = lines.slice(start + 1, end).filter((l) => l.trim() !== "");
    assert.ok(preview.length > 3);
    for (const l of preview) assert.match(l, /^ {2}\+ /);
    assert.match(written(f), /^# \.kit\.toml — generated by kit init$/m);
  });
});

describe("kit init config generation: services", { skip }, () => {
  useFixture();

  it("skips an unknown service from --services and says so", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f, ["--services", "no-such-service-xyz"]);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /unknown service 'no-such-service-xyz' — skipped/);
    assert.equal(existsSync(join(f.dir, ".kit.toml")), true);
  });

  it("accepts an empty --services list as the answer 'none'", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f, ["--services", ""]);
    assert.equal(r.exitCode, 0);
    assert.doesNotMatch(r.out, /unknown service/);
    assert.match(r.out, /Generated \.kit\.toml/);
  });
});

describe("kit init config generation: secrets", { skip }, () => {
  useFixture();

  it("warns about plaintext secrets with file, label and a masked preview", async () => {
    file(f, "requirements.txt", "flask\n");
    // Built at run time so no secret-shaped literal sits in the repo (push protection).
    const fake = ["sk", "live", "abcdefghijklmnop1234567890"].join("_");
    file(f, ".env", `API_KEY=${fake}\n`);
    const r = await init(f, ["--store=env"]);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /Found \d+ plaintext secret\(s\) across 1 file\(s\):/);
    assert.match(r.out, /• \.env {2}.*stripe-key:sk_liv…7890/);
    assert.match(r.out, /These should be migrated to a vault\./);
    assert.match(r.out, /kit secrets migrate/);
    assert.ok(!r.out.includes(fake));
  });

  it("writes the --store flag as the backend and prints its vault note", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f, ["--store=infisical"]);
    assert.equal(r.exitCode, 0);
    assert.match(written(f), /^infisical = "latest"$/m);
    assert.match(r.out, /Secret backend: Infisical/);
    assert.match(r.out, /then authenticate \(your account\):/);
  });

  it("uses a backend the repo is already bound to when no flag is given", async () => {
    file(f, "requirements.txt", "flask\n");
    file(f, ".infisical.json", '{"workspaceId":"w"}\n');
    const r = await init(f);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /Detected infisical config in repo — using it as the secret backend\./);
    assert.match(written(f), /^infisical = "latest"$/m);
  });

  it("writes no [secrets] backend when nothing chose one", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f);
    assert.equal(r.exitCode, 0);
    assert.doesNotMatch(written(f), /^store = /m);
    assert.doesNotMatch(r.out, /Secret backend:/);
  });

  it("seeds secret keys from .env.example and records the template file", async () => {
    file(f, "requirements.txt", "flask\n");
    file(f, ".env.example", "FOO=\nBAR=\n");
    const r = await init(f, ["--store=env"]);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /Seeded 2 key\(s\) from \.env\.example/);
    const toml = written(f);
    assert.match(toml, /^template = "\.env\.example"$/m);
    assert.match(toml, /^FOO = \{ source = "env" \}$/m);
    assert.match(toml, /^BAR = \{ source = "env" \}$/m);
  });

  it("falls back to .env.sample when .env.example is absent", async () => {
    file(f, "requirements.txt", "flask\n");
    file(f, ".env.sample", "TOKEN=\n");
    const r = await init(f, ["--store=env"]);
    assert.match(r.out, /Seeded 1 key\(s\) from \.env\.sample/);
    assert.match(written(f), /^template = "\.env\.sample"$/m);
  });
});

describe("kit init config generation: gaps, flags and extras", { skip }, () => {
  useFixture();

  it("lists package.json scripts as candidates on the setup.verify gap", async () => {
    file(
      f,
      "package.json",
      '{"name":"x","scripts":{"test":"t","build":"b"},"dependencies":{"next":"1"}}',
    );
    const r = await init(f, ["--store=env"]);
    assert.equal(r.exitCode, 0);
    assert.match(r.out, /field\(s\) kit will not infer/);
    assert.match(r.out, /setup\.verify/);
    assert.match(r.out, /found: test, build/);
    assert.match(r.out, /kit init --verify "<command>"/);
  });

  it("takes --verify and --install from the command line into the file", async () => {
    file(f, "package.json", '{"name":"x","dependencies":{"next":"1"}}');
    const r = await init(f, ["--store=env", "--verify", "npm test", "--install", "npm ci"]);
    assert.equal(r.exitCode, 0);
    const toml = written(f);
    assert.match(toml, /npm test/);
    assert.match(toml, /npm ci/);
    assert.doesNotMatch(r.out, /setup\.verify/);
  });

  it("leaves trivy out of [tools] when there is no Dockerfile", async () => {
    file(f, "requirements.txt", "flask\n");
    const r = await init(f, ["--store=env"]);
    assert.equal(r.exitCode, 0);
    assert.ok(!written(f).includes("trivy"));
  });

  it("adds trivy to [tools] when a Dockerfile exists", async () => {
    file(f, "requirements.txt", "flask\n");
    file(f, "Dockerfile", "FROM scratch\n");
    const r = await init(f, ["--store=env"]);
    assert.equal(r.exitCode, 0);
    assert.match(written(f), /^"aqua:aquasecurity\/trivy" = "latest"$/m);
  });
});
