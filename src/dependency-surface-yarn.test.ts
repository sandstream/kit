import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { analyseGraph } from "./dependency-surface.js";
import { graphFromYarnLock, parseYarnLock } from "./dependency-surface-yarn.js";

const V1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@scope/x@^2":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@scope/x/-/x-2.0.0.tgz#abc"

big-a@^1.0.0, big-a@^1.1.0:
  version "1.1.0"
  dependencies:
    shared "^1.0.0"

big@^1.0.0:
  version "1.0.2"
  dependencies:
    big-a "^1.0.0"
    "@scope/x" "^2"

shared@^1.0.0:
  version "1.0.0"

tool-a@^1.0.0:
  version "1.0.0"

tool@^3.0.0:
  version "3.0.0"
  dependencies:
    tool-a "^1.0.0"
    shared "^1.0.0"
`;

const BERRY = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"@scope/x@npm:^2":
  version: 2.0.0
  resolution: "@scope/x@npm:2.0.0"
  checksum: aaa
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  dependencies:
    big: "npm:^1.0.0"
    tool: "npm:^3.0.0"
  languageName: unknown
  linkType: soft

"big-a@npm:^1.0.0, big-a@npm:^1.1.0":
  version: 1.1.0
  resolution: "big-a@npm:1.1.0"
  dependencies:
    shared: "npm:^1.0.0"
  checksum: bbb
  languageName: node
  linkType: hard

"big@npm:^1.0.0":
  version: 1.0.2
  resolution: "big@npm:1.0.2"
  dependencies:
    "@scope/x": "npm:^2"
    big-a: "npm:^1.0.0"
  checksum: ccc
  languageName: node
  linkType: hard

"shared@npm:^1.0.0":
  version: 1.0.0
  resolution: "shared@npm:1.0.0"
  checksum: ddd
  languageName: node
  linkType: hard

"tool-a@npm:^1.0.0":
  version: 1.0.0
  resolution: "tool-a@npm:1.0.0"
  checksum: eee
  languageName: node
  linkType: hard

"tool@npm:^3.0.0":
  version: 3.0.0
  resolution: "tool@npm:3.0.0"
  dependencies:
    shared: "npm:^1.0.0"
    tool-a: "npm:^1.0.0"
  checksum: fff
  languageName: node
  linkType: hard
`;

const manifest = {
  dependencies: { big: "^1.0.0" },
  devDependencies: { tool: "^3.0.0" },
};

describe("parseYarnLock", () => {
  it("reads a classic (v1) lockfile: names, versions, every descriptor of an entry, and dependencies", () => {
    const entries = parseYarnLock(V1);
    assert.ok(entries);
    const bigA = entries.find((e) => e.name === "big-a");
    assert.equal(bigA?.version, "1.1.0");
    assert.deepEqual(bigA?.descriptors, ["big-a@^1.0.0", "big-a@^1.1.0"]);
    assert.deepEqual(bigA?.dependencies, { shared: "^1.0.0" });
    const scoped = entries.find((e) => e.name === "@scope/x");
    assert.equal(scoped?.version, "2.0.0");
    assert.equal(entries.length, 6);
  });

  it("reads a berry (v2 and later) lockfile and leaves out the workspace entry", () => {
    const entries = parseYarnLock(BERRY);
    assert.ok(entries);
    assert.ok(!entries.some((e) => e.name === "app"), "the project itself is not a package");
    const big = entries.find((e) => e.name === "big");
    assert.equal(big?.version, "1.0.2");
    assert.deepEqual(big?.dependencies, { "@scope/x": "npm:^2", "big-a": "npm:^1.0.0" });
    const bigA = entries.find((e) => e.name === "big-a");
    assert.deepEqual(bigA?.descriptors, ["big-a@npm:^1.0.0", "big-a@npm:^1.1.0"]);
    assert.equal(entries.length, 6);
  });

  it("returns null for text that is neither format", () => {
    assert.equal(parseYarnLock("lockfileVersion: 9\npackages:\n"), null);
    assert.equal(parseYarnLock(""), null);
  });
});

describe("analyseGraph over a yarn lockfile", () => {
  for (const [label, text] of [
    ["classic", V1],
    ["berry", BERRY],
  ] as const) {
    it(`${label}: counts shipped and development-only packages from what the manifest reaches`, () => {
      const graph = graphFromYarnLock(text, manifest);
      assert.ok(graph);
      const r = analyseGraph({
        graph,
        manifest,
        usage: { importSites: new Map([["big", 2]]), scriptText: "tool" },
      });
      // shipped: big, big-a, shared, @scope/x. dev only: tool, tool-a. shared is also needed by tool.
      assert.deepEqual(r.totals, {
        direct: 2,
        directProd: 1,
        directDev: 1,
        all: 6,
        shipped: 4,
        devOnly: 2,
      });
    });

    it(`${label}: gives each direct dependency its closure and what only it needs`, () => {
      const graph = graphFromYarnLock(text, manifest);
      assert.ok(graph);
      const r = analyseGraph({
        graph,
        manifest,
        usage: { importSites: new Map(), scriptText: "" },
      });
      const big = r.direct.find((d) => d.name === "big");
      const tool = r.direct.find((d) => d.name === "tool");
      assert.deepEqual({ b: big?.brings, o: big?.onlyThrough }, { b: 3, o: 2 });
      assert.deepEqual({ b: tool?.brings, o: tool?.onlyThrough }, { b: 2, o: 1 });
    });
  }

  it("names what a yarn lockfile cannot tell: no engines and no install-script data", () => {
    const graph = graphFromYarnLock(V1, manifest);
    assert.ok(graph);
    assert.deepEqual(graph.cannotSee, ["engines", "install scripts"]);
  });

  it("finds a package installed in more than one version", () => {
    const text = V1.replace(
      'tool-a@^1.0.0:\n  version "1.0.0"\n',
      'tool-a@^1.0.0:\n  version "1.0.0"\n  dependencies:\n    shared "^2.0.0"\n',
    ).concat('\nshared@^2.0.0:\n  version "2.0.0"\n');
    const graph = graphFromYarnLock(text, manifest);
    assert.ok(graph);
    const r = analyseGraph({ graph, manifest, usage: { importSites: new Map(), scriptText: "" } });
    assert.match(
      r.findings.find((f) => f.rule === "duplicates")?.message ?? "",
      /shared \(1\.0\.0, 2\.0\.0\)/,
    );
  });

  it("leaves out a direct dependency the lockfile does not hold, instead of inventing it", () => {
    assert.equal(
      graphFromYarnLock(V1, { dependencies: { missing: "^1.0.0" } })?.direct.has("missing"),
      false,
      "an unresolved direct dependency is left out, not invented",
    );
  });
});

describe("analyseGraph: direct dependencies the lockfile does not hold", () => {
  it("names the direct dependencies it could not find, so a stale lockfile is visible", () => {
    const m = {
      dependencies: { big: "^1.0.0", gone: "^9.0.0" },
      devDependencies: { tool: "^3.0.0" },
    };
    const graph = graphFromYarnLock(V1, m);
    assert.ok(graph);
    const r = analyseGraph({
      graph,
      manifest: m,
      usage: { importSites: new Map(), scriptText: "" },
    });
    assert.deepEqual(r.unresolvedDirect, ["gone"]);
  });

  it("reports none when every direct dependency is found", () => {
    const graph = graphFromYarnLock(V1, manifest);
    assert.ok(graph);
    const r = analyseGraph({ graph, manifest, usage: { importSites: new Map(), scriptText: "" } });
    assert.deepEqual(r.unresolvedDirect, []);
  });
});

describe("graphFromYarnLock in a monorepo lockfile", () => {
  it("counts only what the project reaches, not the other packages the lockfile also holds", () => {
    const text = `${V1}\nother-app-only@^1.0.0:\n  version "1.0.0"\n  dependencies:\n    other-leaf "^1.0.0"\n\nother-leaf@^1.0.0:\n  version "1.0.0"\n`;
    const graph = graphFromYarnLock(text, manifest);
    assert.ok(graph);
    const names = [...graph.nodes.values()].map((n) => n.name);
    assert.ok(!names.includes("other-app-only"));
    assert.ok(!names.includes("other-leaf"));
    const r = analyseGraph({ graph, manifest, usage: { importSites: new Map(), scriptText: "" } });
    assert.equal(r.totals.all, 6, "the six this project reaches");
  });
});
