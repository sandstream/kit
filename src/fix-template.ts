import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import type { kitConfig } from "./config.js";

/** Create placeholders in the requested project. Preserve any existing file. */
export async function generateSecretsTemplate(
  secrets: kitConfig["secrets"],
  cwd: string,
): Promise<{ path: string; keyCount: number; written: boolean } | undefined> {
  const keyNames = Object.keys(secrets?.keys ?? {});
  if (!secrets?.template || keyNames.length === 0) return undefined;
  const path = resolve(cwd, secrets.template);
  const body = [
    "# Secret placeholders generated by kit fix.",
    "# Keep real values in the project vault.",
    "",
    ...keyNames.map((key) => `${key}=`),
    "",
  ].join("\n");
  try {
    await writeFile(path, body, { encoding: "utf-8", flag: "wx" });
    return { path, keyCount: keyNames.length, written: true };
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
    return { path, keyCount: keyNames.length, written: false };
  }
}
